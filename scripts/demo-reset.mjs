#!/usr/bin/env node
// Prints the SQL that restores the hosted demo to its seeded state (D-043): it
// wipes the two demo organizations and the seed's own logins, then runs the
// demo seed (scripts/demo-seed.mjs) unchanged. DESTRUCTIVE: every visitor change
// in the demo is lost. Run it only with the owner's explicit approval (AGENTS.md
// rule 6), always in one transaction so any failure leaves nothing changed:
//
//   read -s DEMO_PASSWORD && export DEMO_PASSWORD
//   node scripts/demo-reset.mjs | psql "<connection string>" \
//     -v ON_ERROR_STOP=1 --single-transaction -v confirm=reset-demo \
//     -v demo_password="$DEMO_PASSWORD" -v private_password="$(openssl rand -base64 24)"
//
// Guards: it refuses without `-v confirm=reset-demo`, and refuses a database
// that holds any organization other than the two demo ones. See docs/DEPLOYMENT.md.
import { readFileSync } from "node:fs";
import { fileURLToPath } from "node:url";

import { buildDemoSeed } from "./demo-seed.mjs";

const SEED = fileURLToPath(new URL("../supabase/seed.sql", import.meta.url));

/** The seed's organizations: Northwind Shipping and Meridian Tankers. */
export const DEMO_ORGANIZATIONS = ["a0000000-0000-4000-8000-000000000001", "b0000000-0000-4000-8000-000000000001"];

/** The seed's own accounts, as (id, email) pairs from its auth.users values list. */
export function seedUsers(seedSql) {
  const users = [...seedSql.matchAll(/\('([0-9a-f-]{36})'::uuid, '([^']+@[^']+)'/g)].map(([, id, email]) => ({ id, email }));
  if (users.length === 0) {
    throw new Error("Found no seed users in seed.sql (expected ('<uuid>'::uuid, '<email>', ...) rows).");
  }
  return users;
}

export function buildDemoReset(seedSql) {
  const orgs = DEMO_ORGANIZATIONS.map((id) => `'${id}'`).join(", ");
  const users = seedUsers(seedSql)
    .map(({ id }) => `'${id}'`)
    .join(", ");

  return `-- Generated by scripts/demo-reset.mjs. DESTRUCTIVE: restores the demo to its seeded state.
\\if :{?confirm}
\\else
  do $missing$ begin raise exception 'Missing psql variable: -v confirm=reset-demo'; end $missing$;
\\endif
select set_config('aegir.confirm', :'confirm', false) as _confirm \\gset

do $reset_guard$
begin
  if current_setting('aegir.confirm') is distinct from 'reset-demo' then
    raise exception 'Pass -v confirm=reset-demo to wipe and reseed the demo';
  end if;
  if exists (select 1 from public.organizations where id not in (${orgs})) then
    raise exception 'This database has organizations other than the demo ones: refusing to reset it';
  end if;
end;
$reset_guard$;

-- Children before parents (foreign keys). Deletes are audited, so audit rows go last.
delete from public.handovers where organization_id in (${orgs});
delete from public.work_orders where organization_id in (${orgs});
delete from public.inspection_items where organization_id in (${orgs});
delete from public.inspections where organization_id in (${orgs});
delete from public.vessels where organization_id in (${orgs});
delete from public.memberships where organization_id in (${orgs});
delete from public.audit_events where organization_id in (${orgs});
delete from public.organizations where id in (${orgs});
-- The seed's logins (profiles cascade); the seed below recreates them.
delete from auth.users where id in (${users});

${buildDemoSeed(seedSql)}`;
}

if (process.argv[1] === fileURLToPath(import.meta.url)) {
  process.stdout.on("error", (error) => {
    if (error.code === "EPIPE") process.exit(1);
    throw error;
  });
  process.stdout.write(buildDemoReset(readFileSync(SEED, "utf8")));
}
