#!/usr/bin/env node
// Prints the SQL that seeds the hosted demo (D-011, DEPLOYMENT.md step 6) to stdout.
//
// It reuses supabase/seed.sql, the same synthetic data the local stack and the
// pgTAP fixtures use, with one change: the published local password is replaced.
//   - Published demo logins (manager, inspector, technician, viewer) get the
//     password passed to psql as :demo_password.
//   - Everyone else (the administrator, the second technician, the second
//     organization's users) gets :private_password, which is never published.
// No password is written to the repo or to this script's output: psql supplies
// both at run time. Run it once, against an empty database:
//
//   read -s DEMO_PASSWORD && export DEMO_PASSWORD
//   node scripts/demo-seed.mjs | psql "<connection string>" \
//     -v ON_ERROR_STOP=1 --single-transaction \
//     -v demo_password="$DEMO_PASSWORD" -v private_password="$(openssl rand -base64 24)"
//
// See docs/DEPLOYMENT.md for the full procedure.
import { readFileSync } from "node:fs";
import { fileURLToPath } from "node:url";

const SEED = fileURLToPath(new URL("../supabase/seed.sql", import.meta.url));
const LOCAL_HASH = "extensions.crypt('AegirDemo2026', extensions.gen_salt('bf'))";

/** The accounts whose logins are published for the hosted demo (D-011). Never the admin. */
export const PUBLISHED_LOGINS = [
  "marcus.reyes@northwind.example",
  "ingrid.solberg@northwind.example",
  "tomas.okafor@northwind.example",
  "vera.lindqvist@northwind.example",
];

export function buildDemoSeed(seedSql) {
  const occurrences = seedSql.split(LOCAL_HASH).length - 1;
  if (occurrences !== 1) {
    throw new Error(`Expected the local password hash exactly once in seed.sql, found ${occurrences}.`);
  }
  const published = PUBLISHED_LOGINS.map((email) => `'${email}'`).join(", ");
  const demoHash = `extensions.crypt(
        case when u.email in (${published})
          then current_setting('aegir.demo_password')
          else current_setting('aegir.private_password')
        end,
        extensions.gen_salt('bf')
      )`;

  return `-- Generated by scripts/demo-seed.mjs from supabase/seed.sql. Do not edit; regenerate.
-- Passwords come from psql variables (:demo_password, :private_password), never from this file.
\\if :{?demo_password}
\\else
  do $missing$ begin raise exception 'Missing psql variable: -v demo_password=...'; end $missing$;
\\endif
\\if :{?private_password}
\\else
  do $missing$ begin raise exception 'Missing psql variable: -v private_password=...'; end $missing$;
\\endif

-- Session settings, read inside the DO blocks (psql variables don't expand there).
-- \\gset swallows the result row, so the passwords are never echoed to the terminal.
select set_config('aegir.demo_password', :'demo_password', false) as _demo \\gset
select set_config('aegir.private_password', :'private_password', false) as _private \\gset

do $guard$
begin
  if char_length(current_setting('aegir.demo_password')) < 10
     or current_setting('aegir.demo_password') !~ '[A-Za-z]'
     or current_setting('aegir.demo_password') !~ '[0-9]' then
    raise exception 'demo_password must be at least 10 characters with letters and digits (hosted password policy)';
  end if;
  if current_setting('aegir.demo_password') = 'AegirDemo2026' then
    raise exception 'demo_password must not be the published local password';
  end if;
  if current_setting('aegir.private_password') = current_setting('aegir.demo_password') then
    raise exception 'private_password must differ from demo_password';
  end if;
  if exists (select 1 from public.organizations) then
    raise exception 'The database already has organizations: the demo seed only runs on an empty project';
  end if;
end;
$guard$;

${seedSql
    .replace(LOCAL_HASH, demoHash)
    .replace(/^--\s+Every seeded user's password:.*$/m, "--   Passwords: supplied at run time (demo_password for published logins, private_password otherwise).")}`;
}

if (process.argv[1] === fileURLToPath(import.meta.url)) {
  process.stdout.write(buildDemoSeed(readFileSync(SEED, "utf8")));
}
